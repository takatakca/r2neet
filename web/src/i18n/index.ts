const DICTS: Record<Locale, Dict> = { en, fr };

/** Translate with {placeholder} interpolation. Falls back to English. */
export function translate(
  locale: Locale,
  key: string,
  vars: Record<string, string | number> = {},
): string {
  const raw = DICTS[locale][key] ?? DICTS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`,
  );
}

/** Map a backend error code to human copy, never a raw code or stack. */
export function translateError(locale: Locale, code: string | undefined): string {
  if (!code) return translate(locale, 'error.GENERIC');
  const key = `error.${code}`;
  const dict = DICTS[locale];
  if (dict[key] || DICTS.en[key]) return translate(locale, key);
  return translate(locale, 'error.GENERIC');
}

export function formatMoney(cents: number, locale: Locale): string {
  const value = Math.abs(cents) / 100;
  const formatted = new Intl.NumberFormat(locale === 'fr' ? 'fr-CA' : 'en-CA', {
    style: 'currency',
    currency: 'CAD',
  }).format(value);
  return cents < 0 ? `-${formatted}` : formatted;
}

/** (514) 825-2825 while typing, without making anyone type +1. */
export function formatPhoneInput(raw: string): string {
  const d = raw.replace(/\D/g, '').replace(/^1/, '').slice(0, 10);
  if (d.length <= 3) return d;
  if (d.length <= 6) return `(${d.slice(0, 3)}) ${d.slice(3)}`;
  return `(${d.slice(0, 3)}) ${d.slice(3, 6)}-${d.slice(6)}`;
}

export function maskPhoneDisplay(e164: string): string {
  const d = e164.replace(/\D/g, '');
  if (d.length < 10) return '•••';
  return `(${d.slice(1, 4)}) •••-${d.slice(-4)}`;
}
