/**
 * Translations.
 *
 * No customer-visible string is hardcoded in a component. Detection reads
 * navigator.languages on first visit; a manual choice is persisted and always
 * wins, because a Montréal browser set to English does not mean the person
 * wants English.
 */

export type Locale = 'en' | 'fr';

export const LOCALES: { code: Locale; label: string }[] = [
  { code: 'en', label: 'EN' },
  { code: 'fr', label: 'FR' },
];

const STORAGE_KEY = 'r2n_locale';

export function detectLocale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'fr') return stored;
  } catch {
    /* private browsing */
  }
  const langs =
    typeof navigator !== 'undefined'
      ? (navigator.languages ?? [navigator.language ?? 'en'])
      : ['en'];
  for (const l of langs) {
    if (l?.toLowerCase().startsWith('fr')) return 'fr';
    if (l?.toLowerCase().startsWith('en')) return 'en';
  }
  return 'en';
}

export function persistLocale(locale: Locale): void {
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    /* ignore */
  }
}

