export function getService(id: string): ServiceOption {
  const found = SERVICES.find((s) => s.id === id);
  if (!found) throw new Error(`unknown service option: ${id}`);
  return found;
}

export function getAddOn(id: string): AddOn {
  const found = ADD_ONS.find((a) => a.id === id);
  if (!found) throw new Error(`unknown add-on: ${id}`);
  return found;
}
